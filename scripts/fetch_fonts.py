#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = ["fonttools>=4.50", "brotli>=1.1"]
# ///
"""Download the Source font family from Adobe's GitHub releases.

All fonts are Adobe's variable OTF (CFF2) builds. Unlike the Google Fonts
builds they keep all OpenType features, e.g. old-style figures. Two
outputs are generated:

- woff2 files embedded as data URIs in zettlr/source-zettlr-fonts.css for
  the Zettlr editor, whose file protocol cannot serve fonts across origins
- desktop OTF files in typst/fonts/ for the Pandoc/Typst PDF export

Noto Emoji (monochrome, variable) is the emoji fallback in both, so emoji
follow the text color and weight; it only exists as TTF and is converted
to woff2 for Zettlr.

Run with `uv run scripts/fetch_fonts.py` (needs fontTools for woff2).

The OFL license texts are stored next to the Typst fonts.
"""

import base64
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
TYPST_FONT_DIR = ROOT / "typst" / "fonts"
EMBEDDED_CSS = ROOT / "zettlr" / "source-zettlr-fonts.css"

RELEASES = "https://github.com/adobe-fonts/{repo}/releases/download/{tag}/{asset}"
LICENSE = "https://raw.githubusercontent.com/adobe-fonts/{repo}/release/LICENSE.md"

# family, repo, release tag, release asset, {style: member path in the ZIP}
WEB_FONTS = [
    (
        "Source Serif 4",
        "source-serif",
        "4.005R",
        "source-serif-4.005_WOFF2.zip",
        {
            "normal": "source-serif-4.005_WOFF2/VAR/SourceSerif4Variable-Roman.otf.woff2",
            "italic": "source-serif-4.005_WOFF2/VAR/SourceSerif4Variable-Italic.otf.woff2",
        },
    ),
    (
        "Source Sans 3",
        "source-sans",
        "3.052R",
        "WOFF2-source-sans-3.052R.zip",
        {
            "normal": "WOFF2/VF/SourceSans3VF-Upright.otf.woff2",
            "italic": "WOFF2/VF/SourceSans3VF-Italic.otf.woff2",
        },
    ),
    (
        "Source Code Pro",
        "source-code-pro",
        "2.042R-u%2F1.062R-i%2F1.026R-vf",
        "WOFF2-source-code-pro-2.042R-u_1.062R-i_1.026Rvf.zip",
        {
            "normal": "WOFF2/VF/SourceCodeVF-Upright.otf.woff2",
            "italic": "WOFF2/VF/SourceCodeVF-Italic.otf.woff2",
        },
    ),
]

# Desktop variable OTFs for Typst: repo, release tag, release asset, members
DESKTOP_FONTS = [
    (
        "source-serif",
        "4.005R",
        "source-serif-4.005_Desktop.zip",
        [
            "source-serif-4.005_Desktop/VAR/SourceSerif4Variable-Roman.otf",
            "source-serif-4.005_Desktop/VAR/SourceSerif4Variable-Italic.otf",
        ],
    ),
    (
        "source-sans",
        "3.052R",
        "VF-source-sans-3.052R.zip",
        ["VF/SourceSans3VF-Upright.otf", "VF/SourceSans3VF-Italic.otf"],
    ),
    # Static Regular for Mermaid diagrams: Typst draws SVG text with a variable
    # font's default instance, which is ExtraLight for Source Sans 3
    (
        "source-sans",
        "3.052R",
        "OTF-source-sans-3.052R.zip",
        ["OTF/SourceSans3-Regular.otf"],
    ),
    (
        "source-code-pro",
        "2.042R-u%2F1.062R-i%2F1.026R-vf",
        "VF-source-code-VF-1.026R.zip",
        ["VF/SourceCodeVF-Upright.otf", "VF/SourceCodeVF-Italic.otf"],
    ),
]

# Monochrome Noto Emoji from google/fonts, pinned to a commit
NOTO_EMOJI = "https://raw.githubusercontent.com/google/fonts/{rev}/ofl/notoemoji/{name}"
NOTO_EMOJI_REV = "8b0a1d0f5983c89bc2b93f1b5fb55f9e252744b5"
NOTO_EMOJI_FILES = {
    "NotoEmoji%5Bwght%5D.ttf": "NotoEmoji-Variable.ttf",
    "OFL.txt": "OFL-NotoEmoji.txt",
}

FACE = """@font-face {{
    font-family: "{family}";
    font-style: {style};
    font-weight: {weight};
    font-display: swap;
    src: url("{src}") format("woff2");
}}
"""
HEADER = "/* Generated by scripts/fetch_fonts.py — do not edit by hand. */\n\n"


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as response:
        return response.read()


def fetch_noto_emoji() -> dict[str, bytes]:
    return {
        filename: fetch(NOTO_EMOJI.format(rev=NOTO_EMOJI_REV, name=name))
        for name, filename in NOTO_EMOJI_FILES.items()
    }


def to_woff2(data: bytes) -> bytes:
    font = TTFont(io.BytesIO(data))
    font.flavor = "woff2"
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def face(family: str, style: str, weight: str, data: bytes) -> str:
    uri = "data:font/woff2;base64," + base64.b64encode(data).decode()
    return FACE.format(family=family, style=style, weight=weight, src=uri)


def fetch_editor_fonts(emoji: dict[str, bytes]) -> None:
    TYPST_FONT_DIR.mkdir(parents=True, exist_ok=True)
    faces: list[str] = []
    for family, repo, tag, asset, members in WEB_FONTS:
        url = RELEASES.format(repo=repo, tag=tag, asset=asset)
        with zipfile.ZipFile(io.BytesIO(fetch(url))) as archive:
            for style, member in members.items():
                faces.append(face(family, style, "200 900", archive.read(member)))
        license_name = f"OFL-{family.replace(' ', '')}.txt"
        (TYPST_FONT_DIR / license_name).write_bytes(fetch(LICENSE.format(repo=repo)))

    woff2 = to_woff2(emoji["NotoEmoji-Variable.ttf"])
    faces.append(face("Noto Emoji", "normal", "300 700", woff2))
    (TYPST_FONT_DIR / "OFL-NotoEmoji.txt").write_bytes(emoji["OFL-NotoEmoji.txt"])

    EMBEDDED_CSS.write_text(HEADER + "\n".join(faces))
    print(f"  {EMBEDDED_CSS.relative_to(ROOT)}")


def fetch_desktop_fonts(emoji: dict[str, bytes]) -> None:
    TYPST_FONT_DIR.mkdir(parents=True, exist_ok=True)
    for stale in [*TYPST_FONT_DIR.glob("*.ttf"), *TYPST_FONT_DIR.glob("*.otf")]:
        stale.unlink()
    for repo, tag, asset, members in DESKTOP_FONTS:
        url = RELEASES.format(repo=repo, tag=tag, asset=asset)
        with zipfile.ZipFile(io.BytesIO(fetch(url))) as archive:
            for member in members:
                filename = Path(member).name
                (TYPST_FONT_DIR / filename).write_bytes(archive.read(member))
                print(f"  typst/fonts/{filename}")
    (TYPST_FONT_DIR / "NotoEmoji-Variable.ttf").write_bytes(
        emoji["NotoEmoji-Variable.ttf"]
    )
    print("  typst/fonts/NotoEmoji-Variable.ttf")


def main() -> int:
    emoji = fetch_noto_emoji()
    fetch_editor_fonts(emoji)
    fetch_desktop_fonts(emoji)
    return 0


if __name__ == "__main__":
    sys.exit(main())
