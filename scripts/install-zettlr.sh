#!/usr/bin/env bash
# Set up the Source theme in Zettlr (macOS):
# - link the editor theme and import it from custom.css (existing rules are
#   kept; a backup is written first)
# - add the export profile "Source PDF (Typst)" (needs typst on this machine)
# - link the snippet "protokoll" for new meeting notes
#
# Usage: install-zettlr.sh [--uninstall]
set -euo pipefail

repo_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly repo_dir
readonly data_dir="${ZETTLR_DATA_DIR:-${HOME}/Library/Application Support/zettlr}"
readonly custom_css="${data_dir}/custom.css"
readonly import_line='@import url("source-zettlr.css");'
readonly profile_name="Source PDF (Typst).yaml"
readonly profile="${data_dir}/defaults/${profile_name}"
readonly snippet="${data_dir}/snippets/protokoll.tpl.md"

link_item() {
    local source="$1"
    local target="$2"

    if [[ -e "${target}" && ! -L "${target}" ]]; then
        mv "${target}" "${target}.bak"
        echo "Backed up $(basename "${target}") -> $(basename "${target}").bak"
    fi
    ln -sfn "${source}" "${target}"
    echo "Linked $(basename "${target}")"
}

backup_custom_css() {
    local stamp backup n=1
    stamp="$(date +%Y%m%d-%H%M%S)"
    backup="${custom_css}.${stamp}.bak"
    while [[ -e "${backup}" ]]; do
        backup="${custom_css}.${stamp}-${n}.bak"
        n=$((n + 1))
    done
    cp "${custom_css}" "${backup}"
    echo "Backed up custom.css -> $(basename "${backup}")"
}

install_theme() {
    link_item "${repo_dir}/zettlr/source-zettlr.css" "${data_dir}/source-zettlr.css"
    link_item "${repo_dir}/source" "${data_dir}/source"

    if [[ ! -f "${custom_css}" ]]; then
        printf '%s\n' "${import_line}" > "${custom_css}"
        echo "Created custom.css"
    elif grep -qF "${import_line}" "${custom_css}"; then
        echo "custom.css already imports the theme"
    else
        backup_custom_css
        # @import must come before all other rules
        { printf '%s\n\n' "${import_line}"; cat "${custom_css}"; } > "${custom_css}.tmp"
        mv "${custom_css}.tmp" "${custom_css}"
        echo "Added import to custom.css"
    fi
    install_profile
    mkdir -p "$(dirname "${snippet}")"
    link_item "${repo_dir}/zettlr/snippets/protokoll.tpl.md" "${snippet}"
    echo "Done. Restart Zettlr to load the export profile and snippet."
}

find_typst() {
    command -v typst 2>/dev/null && return
    # GUI apps do not see the shell PATH, so look in common install locations
    local candidate
    for candidate in "${HOME}/.local/bin/typst" "${HOME}/.cargo/bin/typst" /opt/homebrew/bin/typst /usr/local/bin/typst; do
        if [[ -x "${candidate}" ]]; then
            echo "${candidate}"
            return
        fi
    done
}

install_profile() {
    local typst
    typst="$(find_typst)"
    if [[ -z "${typst}" ]]; then
        echo "Warning: typst not found, skipping the PDF export profile" >&2
        return
    fi
    mkdir -p "$(dirname "${profile}")"
    sed -e "s|@TYPST@|${typst}|g" -e "s|@REPO@|${repo_dir}|g" \
        "${repo_dir}/zettlr/${profile_name}.in" > "${profile}"
    echo "Wrote export profile ${profile_name} (typst: ${typst})"
}

uninstall_theme() {
    if [[ -f "${custom_css}" ]] && grep -qF "${import_line}" "${custom_css}"; then
        backup_custom_css
        if [[ "$(head -n 2 "${custom_css}")" == "${import_line}" ]]; then
            # Exactly what install added: import line plus one blank line
            tail -n +3 "${custom_css}" > "${custom_css}.tmp"
        else
            grep -vF "${import_line}" "${custom_css}" > "${custom_css}.tmp" || true
        fi
        mv "${custom_css}.tmp" "${custom_css}"
        echo "Removed import from custom.css"
    fi
    if [[ -f "${profile}" ]] && grep -q "Generated by scripts/install-zettlr.sh" "${profile}"; then
        rm "${profile}"
        echo "Removed export profile ${profile_name}"
    fi
    for target in "${data_dir}/source-zettlr.css" "${data_dir}/source" "${snippet}"; do
        if [[ -L "${target}" ]]; then
            rm "${target}"
            echo "Removed link $(basename "${target}")"
        fi
    done
}

main() {
    if [[ ! -d "${data_dir}" ]]; then
        echo "Error: Zettlr data folder not found: ${data_dir}" >&2
        exit 1
    fi
    case "${1:-}" in
        "") install_theme ;;
        --uninstall) uninstall_theme ;;
        *)
            echo "Usage: $(basename "$0") [--uninstall]" >&2
            exit 2
            ;;
    esac
}

main "$@"
